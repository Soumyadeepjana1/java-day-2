public class Forloop2 {
    public static void main(String[] args) {
        for (int i = 100; i >= 1; i--) {
            if (i % 2 == 0) {
                System.out.println("print number is even: " + i);
            } else {
                System.out.println("print number is odd: " + i);
            }
        }
    }

}
